-- SEDCO STS: isolated PostgreSQL core for a NEW, dedicated Supabase project.
-- DOES NOT import legacy MySQL records, create users, or expose the preview to production.
-- Intended for a blank STAGING project, after verifying its organization and ownership.
-- Approval mutations MUST use later audited server-side transactional RPCs; no client DML is allowed.
BEGIN;

CREATE TABLE IF NOT EXISTS public.sts_profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
  legacy_user_id bigint UNIQUE,
  fullname text NOT NULL,
  email text NOT NULL UNIQUE,
  department text,
  job_title text,
  profile_image text,
  role text NOT NULL DEFAULT 'staff' CHECK (role IN (
    'admin','staff','training_section','head_of_department','head_of_division',
    'general_manager','pengerusi_besar','finance'
  )),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- SECURITY DEFINER helpers prevent recursion when policies inspect profile roles.
-- Client code must never be able to assign roles by directly writing profiles.
CREATE OR REPLACE FUNCTION public.sts_current_role()
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
  SELECT p.role FROM public.sts_profiles AS p
  WHERE p.id = (SELECT auth.uid()) AND p.is_active = true LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.sts_is_custodian()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
  SELECT COALESCE((SELECT public.sts_current_role() IN ('admin','training_section')), false);
$$;

CREATE TABLE IF NOT EXISTS public.sts_departments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id bigint UNIQUE,
  name text NOT NULL UNIQUE,
  hod_user_id uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sts_applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  application_no text NOT NULL UNIQUE,
  applicant_id uuid NOT NULL REFERENCES public.sts_profiles(id) ON DELETE RESTRICT,
  parent_application_id uuid REFERENCES public.sts_applications(id) ON DELETE SET NULL,
  form_type text NOT NULL CHECK (form_type IN ('BPL','PKK','TEA')),
  title text NOT NULL,
  department text,
  assigned_hod_id uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','approved','correction','rejected','cancelled')),
  current_stage text NOT NULL DEFAULT 'training'
    CHECK (current_stage IN ('training','hod','gm','chairman','training_final','finance','completed')),
  sla_due_at timestamptz,
  training_start date,
  training_end date,
  followup_due_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  cancellation_reason text,
  review_note text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sts_applications_applicant_idx ON public.sts_applications(applicant_id);
CREATE INDEX IF NOT EXISTS sts_applications_stage_idx ON public.sts_applications(current_stage,status);
CREATE INDEX IF NOT EXISTS sts_applications_hod_idx ON public.sts_applications(assigned_hod_id);
CREATE INDEX IF NOT EXISTS sts_applications_parent_idx ON public.sts_applications(parent_application_id);

CREATE TABLE IF NOT EXISTS public.sts_application_reviews (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  application_id uuid NOT NULL REFERENCES public.sts_applications(id) ON DELETE RESTRICT,
  reviewer_id uuid NOT NULL REFERENCES public.sts_profiles(id) ON DELETE RESTRICT,
  review_stage text NOT NULL CHECK (review_stage IN (
    'training','hod','gm','chairman','training_final','finance'
  )),
  decision text NOT NULL CHECK (decision IN ('approved','rejected','correction')),
  note text,
  reviewed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sts_reviews_application_idx ON public.sts_application_reviews(application_id,reviewed_at);

CREATE TABLE IF NOT EXISTS public.sts_application_drafts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  applicant_id uuid NOT NULL REFERENCES public.sts_profiles(id) ON DELETE CASCADE,
  form_type text NOT NULL CHECK (form_type IN ('BPL','PKK','TEA')),
  parent_application_id uuid REFERENCES public.sts_applications(id) ON DELETE SET NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (applicant_id,form_type)
);

CREATE TABLE IF NOT EXISTS public.sts_application_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  application_id uuid NOT NULL REFERENCES public.sts_applications(id) ON DELETE RESTRICT,
  actor_user_id uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  event_type text NOT NULL,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sts_application_attachments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  application_id uuid NOT NULL REFERENCES public.sts_applications(id) ON DELETE RESTRICT,
  uploaded_by uuid NOT NULL REFERENCES public.sts_profiles(id) ON DELETE RESTRICT,
  original_name text NOT NULL,
  storage_path text NOT NULL,
  mime_type text,
  file_size bigint NOT NULL DEFAULT 0 CHECK (file_size >= 0),
  uploaded_at timestamptz NOT NULL DEFAULT now()
);
-- A private Storage bucket and object-level security policies will be configured
-- separately, only after role tests; never use a public bucket for staff files.

CREATE TABLE IF NOT EXISTS public.sts_calendar_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  title text NOT NULL,
  event_date date NOT NULL,
  event_type text NOT NULL DEFAULT 'company',
  description text,
  created_by uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sts_calendar_date_idx ON public.sts_calendar_events(event_date);

CREATE TABLE IF NOT EXISTS public.sts_notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  user_id uuid NOT NULL REFERENCES public.sts_profiles(id) ON DELETE RESTRICT,
  type text NOT NULL DEFAULT 'info',
  title text NOT NULL,
  message text NOT NULL,
  link text,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz
);
CREATE INDEX IF NOT EXISTS sts_notifications_user_idx ON public.sts_notifications(user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.sts_audit_logs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  user_id uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity_type text,
  entity_id text,
  metadata jsonb,
  ip_address inet,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sts_system_settings (
  setting_key text PRIMARY KEY,
  setting_value text NOT NULL,
  updated_by uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sts_email_queue (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  legacy_id bigint UNIQUE,
  user_id uuid REFERENCES public.sts_profiles(id) ON DELETE SET NULL,
  recipient_email text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  status text NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','sent','failed')),
  attempts integer NOT NULL DEFAULT 0 CHECK(attempts >= 0),
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz
);

-- Mandatory RLS; NO client write policies are intentionally included.
ALTER TABLE public.sts_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_departments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_application_reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_application_drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_application_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_application_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_calendar_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_audit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_system_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sts_email_queue ENABLE ROW LEVEL SECURITY;

-- Policies below permit read access only. Approval, corrections, inserts and
-- management must go through reviewed Edge Functions / SECURITY DEFINER RPC.
CREATE POLICY sts_profiles_self_or_custodian_read
  ON public.sts_profiles FOR SELECT TO authenticated
  USING (id = (SELECT auth.uid()) OR (SELECT public.sts_is_custodian()));
CREATE POLICY sts_departments_authenticated_read
  ON public.sts_departments FOR SELECT TO authenticated USING (true);
CREATE POLICY sts_applications_owner_or_custodian_read
  ON public.sts_applications FOR SELECT TO authenticated
  USING (applicant_id = (SELECT auth.uid()) OR (SELECT public.sts_is_custodian()));
-- Reviewer-stage access requires a dedicated sanitized RPC rather than
-- direct SELECT of payload containing other reviewers' signatures.
CREATE POLICY sts_reviews_owner_or_custodian_read
  ON public.sts_application_reviews FOR SELECT TO authenticated
  USING (
    reviewer_id = (SELECT auth.uid()) OR (SELECT public.sts_is_custodian())
    OR EXISTS (SELECT 1 FROM public.sts_applications AS a
               WHERE a.id = application_id AND a.applicant_id = (SELECT auth.uid()))
  );
CREATE POLICY sts_drafts_owner_or_custodian_read
  ON public.sts_application_drafts FOR SELECT TO authenticated
  USING (applicant_id = (SELECT auth.uid()) OR (SELECT public.sts_is_custodian()));
CREATE POLICY sts_versions_owner_or_custodian_read
  ON public.sts_application_versions FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.sts_applications AS a
    WHERE a.id = application_id AND
          (a.applicant_id = (SELECT auth.uid()) OR (SELECT public.sts_is_custodian()))
  ));
CREATE POLICY sts_attachments_owner_or_custodian_read
  ON public.sts_application_attachments FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.sts_applications AS a
    WHERE a.id = application_id AND
          (a.applicant_id = (SELECT auth.uid()) OR (SELECT public.sts_is_custodian()))
  ));
CREATE POLICY sts_calendar_events_authenticated_read
  ON public.sts_calendar_events FOR SELECT TO authenticated USING (true);
CREATE POLICY sts_notifications_self_read
  ON public.sts_notifications FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()));

-- No client-facing policies for audit logs, email queue, settings.
-- Explicitly restrict helper execution to authenticated caller, not anon.
REVOKE ALL ON FUNCTION public.sts_current_role() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.sts_is_custodian() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.sts_current_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.sts_is_custodian() TO authenticated;

COMMIT;
